const dicts: Record<Lang, Record<TKey, string>> = { ru, uz_lat, uz_cyr, en };

function plural(lang: Lang, n: number, forms: string[]): string {
  if (lang === 'ru') {
    const a = Math.abs(n) % 100, b = a % 10;
    if (a > 10 && a < 20) return forms[2] ?? forms[0];
    if (b > 1 && b < 5) return forms[1] ?? forms[0];
    if (b === 1) return forms[0];
    return forms[2] ?? forms[0];
  }
  if (lang === 'en') return forms[n === 1 ? 0 : 1] ?? forms[0];
  return forms[0];
}

export type TT = (key: TKey, vars?: Record<string, string | number>) => string;

/** Словарь кабинета преподавателя на языке приложения. */
export function useTT(): TT {
  const { lang } = useI18n();
  return (key, vars) => {
    let s = dicts[lang][key] ?? ru[key];
    if (s.includes('|')) s = plural(lang, Number(vars?.n ?? 0), s.split('|'));
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
    return s;
  };
}
